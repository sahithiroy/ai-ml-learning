'''
Comparison operators are used to compare two values. They return a boolean value (True or False) based on the comparison.
The following comparison operators are available in Python:
1. **Equal to (==)**: Returns True if the values of both operands are equal.
2. **Not equal to (!=)**: Returns True if the values of both operands are not equal.
3. **Greater than (>)**: Returns True if the value of the left operand is greater than the value of the right operand.
4. **Less than (<)**: Returns True if the value of the left operand is less than the value of the right operand.
5. **Greater than or equal to (>=)**: Returns True if the value of the left operand is greater than or equal to the value of the right operand.
6. **Less than or equal to (<=)**: Returns True if the value of the left operand is less than or equal to the value of the right operand.

'''
# Equal to
a = 10
b = 5
print("Equal to:", a == b)  # Output: False 

# Not equal to
print("Not equal to:", a != b)  # Output: True

# Greater than
print("Greater than:", a > b)  # Output: True

# Less than
print("Less than:", a < b)  # Output: False

#Greater than or equal to
print('Greater than or equal to',a>=b) #Output: True

#less than or equal to
print('Less than or equal to',a<=b) #Output: False