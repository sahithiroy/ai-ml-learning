'''
Arithmetic Operators in Python
Arithmetic operators are used to perform mathematical operations between numeric values. Python supports the following arithmetic operators:

1. **Addition (+)**: Adds two values.
2. **Subtraction (-)**: Subtracts the second value from the first.
3. **Multiplication (*)**: Multiplies two values.
4. **Division (/)**: Divides the first value by the second.
5. **Floor Division (//)**: Divides the first value by the second and returns the quotient as an integer.
6. **Modulus (%)**: Returns the remainder of the division of the first value by the second.
7. **Exponentiation (**)**: Raises the first value to the power of the second.

'''
# Addition
a = 10
print("Addition:", a + 5)  # Output: 15
# Subtraction
print("Subtraction:", a - 5)  # Output: 5
# Multiplication
print("Multiplication:", a * 5)  # Output: 50
# Division
print("Division:", a / 5)  # Output: 2.0
# Floor Division
print("Floor Division:", a // 3)  # Output: 3
# Modulus
print("Modulus:", a % 3)  # Output: 1
# Exponentiation
print("Exponentiation:", a ** 2)  # Output: 100


#Difference between / and // operators
'''
The division operator (/) returns a float value, while the floor division operator (//) returns an integer value.
'''